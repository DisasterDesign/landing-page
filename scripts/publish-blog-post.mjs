async function main() {
  try {
    // מצא את המשתמש הראשון (אדמין) כמחבר
    const author = await prisma.user.findFirst();
    if (!author) {
      console.error("❌ לא נמצא משתמש במסד הנתונים. יש להתחבר לדשבורד קודם.");
      process.exit(1);
    }

    console.log(`👤 מחבר: ${author.name || author.email}`);

    // בדוק אם כבר קיים פוסט עם אותו slug
    const existing = await prisma.blogPost.findUnique({
      where: { slug: blogPost.slug },
    });

    if (existing) {
      console.log(`⚠️  פוסט עם slug "${blogPost.slug}" כבר קיים (id: ${existing.id})`);
      console.log(`   כותרת: ${existing.title}`);
      console.log(`   סטטוס: ${existing.published ? "מפורסם" : "טיוטה"}`);
      console.log(`\n   כדי לעדכן, היכנס לדשבורד: /admin/blog/${existing.id}/edit`);
      process.exit(0);
    }

    // צור את הפוסט
    const post = await prisma.blogPost.create({
      data: {
        ...blogPost,
        authorId: author.id,
      },
    });

    console.log(`\n✅ הפוסט נוצר בהצלחה!`);
    console.log(`   ID: ${post.id}`);
    console.log(`   כותרת: ${post.title}`);
    console.log(`   Slug: ${post.slug}`);
    console.log(`   סטטוס: טיוטה (לא מפורסם)`);
    console.log(`\n📝 לעריכה: /admin/blog/${post.id}/edit`);
    console.log(`🌐 לצפייה (אחרי פרסום): /blog/${post.slug}`);
    console.log(`\n💡 כדי לפרסם, היכנס לדשבורד ולחץ "פרסם", או הרץ:`);
    console.log(`   npx prisma db execute --stdin <<< "UPDATE \\"BlogPost\\" SET published=true, \\"publishedAt\\"=NOW() WHERE id='${post.id}';"`);
  } catch (error) {
    console.error("❌ שגיאה:", error.message);
  } finally {
    await prisma.$disconnect();
  }
}

main();
