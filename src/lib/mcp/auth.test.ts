import assert from 'node:assert/strict';
import test from 'node:test';
import { generateKeyPair, SignJWT } from 'jose';

test('resource auth verifies token then rereads expiring grant and actual app user on every request', async () => {
 const mod = await import('./auth').catch(() => null);
 assert.ok(mod, 'MCP authentication implementation must exist');
 const { privateKey, publicKey } = await generateKeyPair('RS256');
 const now = Math.floor(Date.now()/1000);
 const config = { issuer:'https://identity.example.invalid/', audience:'https://app.example.invalid/api/mcp', jwksUri:'https://identity.example.invalid/.well-known/jwks.json' };
 const sign = (extra: Record<string,unknown> = {}) => new SignJWT({scope:'finance:read clients:read debtors:read',azp:'personal-client',...extra}).setProtectedHeader({alg:'RS256'}).setIssuer(typeof extra.iss==='string'?extra.iss:config.issuer).setAudience(typeof extra.aud==='string'?extra.aud:config.audience).setSubject('subject').setIssuedAt(now).setExpirationTime(typeof extra.exp==='number'?extra.exp:now+300).sign(privateKey);
 const user = {id:'actual-elad',isOwner:true,role:'ADMIN' as const,revenueSharePct:null,mustChangePassword:false};
 const grant = {userId:user.id,issuer:config.issuer,subject:'subject',clientId:'personal-client',scopes:['finance:read','clients:read','debtors:read'],expiresAt:new Date(Date.now()+3600000),notBefore:new Date((now-5)*1000),revokedAt:null as Date|null};
 let reads=0;
 const deps = {verify: async(token:string) => (await import('jose')).jwtVerify(token,publicKey,{issuer:config.issuer,audience:config.audience,algorithms:['RS256'],requiredClaims:['exp','iat','sub']}),loadGrant:async()=>{reads++;return {...grant,user:{...user}};}};
 const request = (token?:string) => new Request(config.audience,{headers:token?{Authorization:`Bearer ${token}`}:{}});
 await assert.rejects(()=>mod.authenticateMcp(request(),config,deps));
 await assert.rejects(()=>mod.authenticateMcp(request('invalid'),config,deps));
 const token=await sign();
 assert.equal((await mod.authenticateMcp(request(token),config,deps)).viewer.userId,user.id);
 user.isOwner=false;
 assert.equal((await mod.authenticateMcp(request(token),config,deps)).viewer.isOwner,false);
 grant.revokedAt=new Date();
 await assert.rejects(()=>mod.authenticateMcp(request(token),config,deps));
 grant.revokedAt=null;grant.expiresAt=new Date(0);
 await assert.rejects(()=>mod.authenticateMcp(request(token),config,deps));
 assert.equal(reads,4);
 grant.expiresAt=new Date(Date.now()+3600000);
 assert.equal((await mod.authenticateMcp(request(await sign({azp:undefined,client_id:'personal-client'})),config,deps)).viewer.userId,user.id);
 await assert.rejects(async()=>mod.authenticateMcp(request(await sign({client_id:'different-client'})),config,deps));
 await assert.rejects(async()=>mod.authenticateMcp(request(await sign({exp:now-1})),config,deps));
 await assert.rejects(async()=>mod.authenticateMcp(request(await sign({aud:'wrong'})),config,deps));
 grant.expiresAt=new Date(Date.now()+3600000);
 await assert.rejects(async()=>mod.authenticateMcp(request(await sign({iss:'https://attacker.invalid/'})),config,deps));
 grant.notBefore=new Date(Date.now()+3600000);await assert.rejects(()=>mod.authenticateMcp(request(token),config,deps));grant.notBefore=new Date((now-5)*1000);
 user.mustChangePassword=true;await assert.rejects(()=>mod.authenticateMcp(request(token),config,deps));user.mustChangePassword=false;
 await assert.rejects(()=>mod.authenticateMcp(request(token),config,{...deps,loadGrant:async()=>null}));
 user.role='MEMBER' as 'ADMIN';
 await assert.rejects(()=>mod.authenticateMcp(request(token),config,deps));
});
